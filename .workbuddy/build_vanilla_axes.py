def _selfcheck():
    """设计稿自检：区域划分必须严丝合缝，否则会出现没人管的漏色像素。"""
    sets = {'RIM': RIM, 'JOINT': JOINT, 'CORE': CORE, 'FACE': FACE}
    head = [p for s in sets.values() for p in s]
    head_set = set(head)
    assert len(head) == len(head_set) == 40, (
        '斧头四区应有 40 个不重复像素, 实得 %d / 去重 %d' % (len(head), len(head_set)))
    assert len(HAFT) == len(set(HAFT)) == 20, '柄应有 20 个不重复像素'
    assert not (head_set & _HAFT_SET), '斧头与柄的坐标有重叠'

    # 掩码自洽：头 40 + 柄 20 必须与原版斧的 alpha **逐像素**对应
    from PIL import Image
    for n in ('iron_axe', 'diamond_axe', 'netherite_axe', 'golden_axe'):
        px = Image.open(os.path.join(REF, n + '.png')).convert('RGBA').load()
        mask = {(x, y) for y in range(16) for x in range(16) if px[x, y][3] > 0}
        assert len(mask) == 60, '%s 掩码 %d 像素, 预期 60' % (n, len(mask))
        assert mask == head_set | _HAFT_SET, '%s 掩码与「头40+柄20」不一致' % n

    # 每件将要落的 extra / acc 坐标都要真存在，否则是白写的一行
    for sp in SPECS:
        for (x, y), _c in sp['extra']:
            assert 0 <= x < 16 and 0 <= y < 16, '%s extra 越界 (%d,%d)' % (sp['key'], x, y)
        for pts, _c in sp['acc']:
            pass                      # predicate 形态无法静态取点
    print('区域自检: 斧头四区 40 + 柄 20 = 60 像素, 与四把原版斧掩码逐像素一致 ✓')


