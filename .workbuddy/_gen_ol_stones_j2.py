def mask(rows):
    return tuple(ch != '.' for row in rows for ch in row)


def dist(a, b):
    return sum(x != y for x, y in zip(a, b))


def main():
    old_masks = {cid: mask(rows) for cid, _c, _n, _m, _col, rows in OLD28}
    mine, fail = {}, []
    for cid, cat, motif, colour, rows in NEW:
        assert len(rows) == 9 and all(len(r) == 9 and set(r) <= set('.#+') for r in rows), cid
        m = mask(rows)
        n = sum(m)
        if n < 15:
            fail.append('%s 只有 %d 格(<15)' % (cid, n))
        mine[cid] = m
        for oid, om in old_masks.items():
            if dist(m, om) < 8:
                fail.append('%s vs 旧 %s 只差 %d 格' % (cid, oid, dist(m, om)))
    ids = list(mine)
    for i in range(len(ids)):
        for j in range(i + 1, len(ids)):
            d = dist(mine[ids[i]], mine[ids[j]])
            if d < 8:
                fail.append('%s vs %s 只差 %d 格' % (ids[i], ids[j], d))
    if fail:
        print('刻纹不合格 %d 条:' % len(fail))
        for f in fail:
            print('  -', f)
        return 1

    blobs = set()
    for cid, cat, motif, colour, rows in NEW:
        im = render(cat, colour, rows)
        assert im.size == (16, 16)
        assert set(im.getchannel('A').histogram()[1:255]) == {0}
        if im.tobytes() in blobs:
            print('!! 贴图重复:', cid)
            return 1
        blobs.add(im.tobytes())
        im.save(os.path.join(TEX, 'ol_%s.png' % cid))
        io.open(os.path.join(MOD, 'ol_%s.json' % cid), 'w', encoding='utf-8').write(
            '{\n  "parent": "minecraft:item/generated",\n'
            '  "textures": {\n    "layer0": "sweetdream:item/stone/ol_%s"\n  }\n}\n' % cid)
        print('png %-16s %-8s %-6s 刻痕=%2d' % (cid, cat, colour, sum(mine[cid])))
    print('done', len(NEW), '颗 | 与旧 28 颗两两差异 >= 8 格')
    return 0


if __name__ == '__main__':
    sys.exit(main())
