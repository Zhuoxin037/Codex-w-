def tagstr(tags):
    return " / ".join(f"{TAG_CN.get(t,t)} {t}" for t in tags) if tags else "（无标签）"


def blocks(segs):
    """把一个 ✦ 段内的所有行合成一行（｜ 分隔）。
    目的：不靠缩进表达层级 —— 粘到笔记软件里缩进会被吃掉，一行一段最稳。"""
    out = []
    for s in segs:
        if s.startswith("✦") or not out:
            out.append([s])
        else:
            out[-1].append(s)
    return ["｜".join(x) for x in out]


def group_lore(lines):
    """把 lore 显示行还原成语义段落：
    ✦ 标题行 与 拼色行（魔力 N · 冷却 N 秒）各自单独成行，
    其余行是游戏内的折行，合并成一段。"""
    out, brk = [], True
    for ln in lines:
        s = ln.strip()
        if not s:
            continue
        is_head = s.startswith("✦")
        is_cost = ("魔力" in s and "冷却" in s) or s.startswith("套装效果")
        if "●" in s and not is_head:          # 套装成员行（● 候潮　● 滩纹）
            if out and "●" in out[-1]:
                out[-1] += "　" + s
            else:
                out.append(s)
            brk = True
        elif is_head or is_cost:
            out.append(s)
            brk = True          # 标题行 / 拼色行之后，正文必须另起一段
        elif brk or not out:
            out.append(s)
            brk = False
        else:
            out[-1] += s
    return out

