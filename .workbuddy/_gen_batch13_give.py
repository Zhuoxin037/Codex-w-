def build(it):
    lore = rebuild(pad_sections(it["lore"]))
    zx = ['"%s"' % it["eid"]]
    if it["cat"] == "armor":
        zx.append('"%s"' % it["slot"])
        zx.append('"armor"')
    else:
        zx.append('"bow"')
    comps = []
    comps.append('item_name={text:"%s",bold:true,color:%s}' % (it["cn"], it["color"]))
    comps.append("lore=%s" % json_to_snbt(lore))
    comps.append("unbreakable={}")
    comps.append("custom_data={zx:[%s],tags:%s}" % (",".join(zx), json_to_snbt(it["tags"])))
    if it.get("ench"):
        # 依附魔回调的装备必须带上四件套（坑 140）: enchantments + glint 关闭
        #   + tooltip 隐藏 enchantments。少任何一件都会"静默失效"或说明多一行。
        comps.append('enchantments={"sweetdream:%s":1}' % it["ench"])
        comps.append("enchantment_glint_override=false")
        comps.append('tooltip_display={hidden_components:["unbreakable","enchantments"]}')
    else:
        comps.append('tooltip_display={hidden_components:["unbreakable"]}')
    return "give @s %s[%s]" % (it["base"], ",".join(comps))


def main():
    write = "--write" in sys.argv
    for it in ITEMS:
        d = os.path.join(BASE, it["key"])
        p = os.path.join(d, "give.mcfunction")
        body = "%s\n%s\n" % (it["note"], build(it))
        if not write:
            print("---- %s" % p)
            print(body)
            continue
        os.makedirs(d, exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(body)
        print("[写] %s" % p)


if __name__ == "__main__":
    main()
