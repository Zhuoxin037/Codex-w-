VALUE_COLOR = {'魔力': 'aqua', '冷却': 'yellow', '伤害': 'yellow'}


def build_lore(segs):
    """把段落表编成 lore 列表（未折行），交给 rebuild 规范化。"""
    lore = []
    for kind, payload in segs:
        if kind == 'head':
            # ★ 每段之间空一行（与包内一致）；若上一行已经是空行则不重复加
            if lore and not (isinstance(lore[-1], dict) and lore[-1].get('text') == ' '
                             and 'extra' not in lore[-1]):
                lore.append({'text': ' ', 'italic': False})
            lore.append({'text': payload, 'color': 'gold', 'bold': True, 'italic': False})
        elif kind == 'info':
            extra = []
            for i, (label, val) in enumerate(payload):
                if i:
                    extra.append({'text': '   ·   ', 'color': 'dark_gray'})
                extra.append({'text': label + ' ', 'color': 'gray'})
                extra.append({'text': val, 'color': VALUE_COLOR.get(label, 'yellow')})
            lore.append({'text': '', 'italic': False, 'extra': extra})
            lore.append({'text': ' ', 'italic': False})
        elif kind == 'para':
            # 段落里用 \n 表示"同段内的换行/段内空行"，逐行铺成正文条目
            parts = payload.split('\n')
            for p in parts:
                if p == '':
                    lore.append({'text': ' ', 'italic': False})
                else:
                    lore.append({'text': p, 'color': 'gray', 'italic': False})
    return lore


def render(lore):
    out = []
    for e in lore:
        if not isinstance(e, dict):
            continue
        t = e.get('text', '')
        ex = e.get('extra')
        if ex:
            t += ''.join(seg.get('text', '') for seg in ex)
        out.append(t)
    return out


