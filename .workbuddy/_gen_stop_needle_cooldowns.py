"""Build/check stop_needle's complete catalog of skills from both source packs.

The framework stores cooldowns as a compound whose keys commands cannot enumerate.
Collect declared skill IDs, including item components, to cover unequipped skills.
Default: read-only drift check. --write updates only the generated cd_all function.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'sweetdream/data/sweetdream/function/equipment/staff/stop_needle/cd_all.mcfunction'
SKILL = re.compile(r'\bskill\s*:\s*"([a-z0-9_.:/-]+)"')
SET_SKILL = re.compile(r'\barg\.skill set value "([a-z0-9_.:/-]+)"')


def catalog():
    skills = set()
    for pack in ('sweetdream', 'manacore-1.0.0'):
        for path in (ROOT / pack / 'data').rglob('*.mcfunction'):
            if path == OUTPUT:
                continue
            for line in path.read_text(encoding='utf-8-sig').splitlines():
                if line.lstrip().startswith('#'):
                    continue
                skills.update(SKILL.findall(line))
                skills.update(SET_SKILL.findall(line))
    return sorted(skills)


def render(skills):
    lines = [
        '# Generated by .workbuddy/_gen_stop_needle_cooldowns.py; do not hand edit.',
        '# Input: manacore:in arg.uuid / arg.seconds. Reduce existing records only.',
        '# Includes unequipped skills; does not create missing cooldown records.',
    ]
    for skill in skills:
        lines.append(f'data modify storage manacore:in arg.skill set value "{skill}"')
        lines.append('function manacore:api/cooldown/reduce')
    return '\n'.join(lines) + '\n'


def main():
    skills = catalog()
    expected = render(skills)
    if '--write' in sys.argv:
        OUTPUT.write_text(expected, encoding='utf-8', newline='\n')
    matches = OUTPUT.exists() and OUTPUT.read_text(encoding='utf-8') == expected
    print(f'stop_needle cooldown catalog: {len(skills)} skills; drift={int(not matches)}')
    return int(not matches)


if __name__ == '__main__':
    raise SystemExit(main())
